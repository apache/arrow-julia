function verify_Message(bytes::Vector{UInt8}, pos::Int64, ctx::VerifyContext, depth::Base.Int)
    t = _vtable(bytes, pos)
    _vvisit!(ctx, "Message")
    depth <= ctx.maxdepth || _vfail("metadata nesting exceeds limit")
    _venum(t, 0, 2, (0x0000000000000000, 0x0000000000000001, 0x0000000000000002, 0x0000000000000003, 0x0000000000000004,))
    tagp = _vfield(t, 1, 1; required=true)
    tag = tagp === nothing ? 0x00 : _vu8(bytes, tagp)
    tag != 0x00 || _vfail("Message.header union tag is required")
    valp = _vref(t, 2; required=true)
    if tag == 0x00
        valp === nothing ||
            _vfail("Message.header union has a value but no tag")
    elseif tag == 0x01
        valp === nothing &&
            _vfail("Message.header union has a tag but no value")
        verify_Schema(bytes, valp, ctx, depth + 1)
    elseif tag == 0x02
        valp === nothing &&
            _vfail("Message.header union has a tag but no value")
        verify_DictionaryBatch(bytes, valp, ctx, depth + 1)
    elseif tag == 0x03
        valp === nothing &&
            _vfail("Message.header union has a tag but no value")
        verify_RecordBatch(bytes, valp, ctx, depth + 1)
    elseif tag == 0x04
        _vfail("Message.header union member Tensor is outside the generated schemas")
    elseif tag == 0x05
        _vfail("Message.header union member SparseTensor is outside the generated schemas")
    else
        _vfail("Message.header union has unknown tag")
    end
    _vfield(t, 3, 8)
    _vtablevector(t, 4, verify_KeyValue, ctx, depth)
    return nothing
end

function verifyroot_Message(bytes::Vector{UInt8}, ctx::VerifyContext)
    length(bytes) >= 4 || _vfail("missing root offset")
    root = Int64(_vu32(bytes, Int64(0)))
    root >= 4 || _vfail("invalid root offset")
    verify_Message(bytes, root, ctx, 0)
    return nothing
end

