function verify_RecordBatch(bytes::Vector{UInt8}, pos::Int64, ctx::VerifyContext, depth::Base.Int)
    t = _vtable(bytes, pos)
    _vvisit!(ctx, "RecordBatch")
    depth <= ctx.maxdepth || _vfail("metadata nesting exceeds limit")
    _vfield(t, 0, 8)
    _vvector(t, 1, 16, ctx)
    _vvector(t, 2, 16, ctx)
    p = _vref(t, 3)
    p === nothing || verify_BodyCompression(bytes, p, ctx, depth + 1)
